async def generate_audio(text, output_path):
    """Generate Arabic audio using edge-tts"""
    communicate = edge_tts.Communicate(text, VOICE, rate="-10%")
    
    with open(output_path, "wb") as f:
        async for chunk in communicate.stream():
            if chunk["type"] == "audio":
                f.write(chunk["data"])

    file_size = os.path.getsize(output_path) if os.path.exists(output_path) else 0
    print(f"   حجم الصوت: {file_size / (1024*1024):.1f} MB")
    
    dur_result = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "default=noprint_wrappers=1:nokey=1", output_path],
        capture_output=True, text=True, timeout=10
    )
    duration = float(dur_result.stdout.strip()) if dur_result.stdout.strip() else 0
    print(f"   مدة الصوت: {duration/60:.1f} دقيقة ({duration:.0f} ثانية)")
    
    return duration


def get_full_script_text(script):
    """Combine all script parts into narration text. Auto-extends short scripts to 15 minutes."""
    parts = []
    if script.get("intro"):
        parts.append(script["intro"])
    paragraphs = script.get("paragraphs", [])
    for paragraph in paragraphs:
        parts.append(paragraph)
    if script.get("conclusion"):
        parts.append(script["conclusion"])
    
    text = " . ".join(parts) + " ."
    word_count = len(text.split())
    
    # Auto-extend: if less than 1000 words (~7 min), repeat to reach ~15 min (1300 words)
    target_words = 1300
    if word_count < 1000 and len(paragraphs) > 0:
        print(f"   ⚠️ سكربت قصير ({word_count} كلمة) - تمديد تلقائي لـ {target_words} كلمة...")
        # Repeat paragraphs in different order with variation
        extended_paragraphs = list(paragraphs)
        multiplier = (target_words // word_count) + 1
        for round_num in range(multiplier):
            shuffled = list(paragraphs)
            random.shuffle(shuffled)
            extended_paragraphs.extend(shuffled)
        
        # Rebuild text with extended paragraphs
        parts = []
        if script.get("intro"):
            parts.append(script["intro"])
        for paragraph in extended_paragraphs[:target_words // (word_count // max(1, len(paragraphs)))]:
            parts.append(paragraph)
        if script.get("conclusion"):
            parts.append(script["conclusion"])
        
        text = " . ".join(parts) + " ."
        new_word_count = len(text.split())
        print(f"   ✅ تم التمديد: {new_word_count} كلمة")
    
    return text


