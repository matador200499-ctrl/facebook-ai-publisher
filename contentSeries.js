function getNextTopic() {
  const state = require("./contentState");

  let index = Number(state.currentIndex || 0);

  if (index >= topics.length) {
    index = 0;
  }

  const topic = topics[index];

  return {
    topic,
    nextIndex: (index + 1) % topics.length
  };
}

